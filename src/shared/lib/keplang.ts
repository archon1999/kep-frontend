import type { Monaco } from '@monaco-editor/react';

export const registerKEPLang = (monaco: Monaco) => {
  if (monaco.languages.getLanguages().some(({ id }: { id: string }) => id === 'keplang')) return;
  monaco.languages.register({ id: 'keplang', extensions: ['.kep'], aliases: ['KEPLang'] });
  monaco.languages.setLanguageConfiguration('keplang', {
    comments: { lineComment: '//' },
    brackets: [
      ['{', '}'],
      ['[', ']'],
      ['(', ')'],
    ],
    autoClosingPairs: [
      { open: '{', close: '}' },
      { open: '[', close: ']' },
      { open: '(', close: ')' },
      { open: '"', close: '"' },
      { open: "'", close: "'" },
    ],
  });
  monaco.languages.setMonarchTokensProvider('keplang', {
    keywords: [
      'agar',
      'bosa',
      'bomasa',
      'to',
      'toki',
      'bolincha',
      'aylan',
      'shundat',
      'qaytar',
      'toxta',
      'tuzilma',
      'davom',
      'at',
      'ni',
      'dab',
      'ol',
    ],
    types: ['son', 'matn', 'mantiq', 'lugat', 'toplam', 'kasr', 'belgi', 'juft'],
    builtins: [
      'juft',
      'matn_at',
      'son_at',
      'kasr_at',
      'massiv',
      'oxirgi',
      'almashtir',
      'uqi',
      'uqi_soz',
      'uqi_satr',
      'chiqar',
      'uzunligi',
      'sarala',
      'qosh',
      'bomi',
      'uchir',
      'qiymat',
      'uqi_kasr',
      'chiqar_aniq',
      'son',
      'kasr',
      'belgi',
      'kod',
      'min',
      'max',
      'abs',
      'ekub',
      'ekuk',
      'daraja',
      'ildiz',
      'pasa',
      'dapaya',
      'yaxlitla',
      'bit_soni',
      'tarsina',
      'oxirini_ol',
      'quyi_chegara',
      'yuqori_chegara',
      'al',
      'al_soz',
      'al_satr',
    ],
    tokenizer: {
      root: [
        [/\/\/.*$/, 'comment'],
        [/"(?:[^"\\]|\\.)*"/, 'string'],
        [/'(?:[^'\\]|\\.)*'/, 'string'],
        [/\b(?:rast|yalgan)\b/, 'keyword'],
        [/\b(?:son|kasr|belgi|juft)(?=\s*\()/, 'predefined'],
        [/\bb\b(?=\s*\.)/, 'predefined'],
        [/\b[a-zA-Z_]\w*(?=\s*\([\w\s,]*\)\s*ni\b)/, 'type.identifier'],
        [
          /[a-zA-Z_]\w*/,
          {
            cases: {
              '@keywords': 'keyword',
              '@types': 'type',
              '@builtins': 'predefined',
              '@default': 'identifier',
            },
          },
        ],
        [/\d+\.\d+(?:[eE][+-]?\d+)?|\d+[eE][+-]?\d+/, 'number.float'],
        [/\d+/, 'number'],
        [/[{}()[\]]/, '@brackets'],
        [/[+\-*/%=!<>|&^~.:]+/, 'operator'],
      ],
    },
  });
};
